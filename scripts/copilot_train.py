#!/usr/bin/env python3
"""Train the copilot's decision tree offline and export it to C.

Input:  results/copilot/bench_train.csv.gz and bench_test.csv.gz (tools/copilot_gen.c: the offline test bench, with the
        same plant, ventilator and breath features that run in QNX; different patients in each file).
Output: src/copilot_tree.h                     the tree as C arrays (generated; do not edit)
        tareas/05_tree/test_vectors.h          held-out vectors + sklearn's answers, for the user's task 5
        results/copilot/train_report.txt       cross-validation, test metrics, confusion matrix, importances
        results/copilot/tree_rules.txt         the whole tree as readable if/else rules

What is learned here: only the split features and thresholds of the tree (which question to ask, in which order).
Everything the copilot then *suggests* comes from a fixed table, and safety_mon validates it with fixed limits.

Needs scikit-learn (not in the system Python): ~/.venvs/breathguard/bin/python scripts/copilot_train.py
"""
import csv
import datetime
import gzip
import os
import sys

import numpy as np
import sklearn
from sklearn.model_selection import GroupKFold
from sklearn.tree import DecisionTreeClassifier, export_text

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results", "copilot")
FEATURES = ["vcv", "leak_frac", "cdyn_ml", "p_res", "tau_exp", "q_ee", "qei_rel", "g_insp"]  # = bf_names[]
CLASSES = ["normal", "leak", "high_r", "low_c"]
LEAK_MIN = 0.08          # a "leak" scenario whose true leak is below 8 % of Vt is not labelled leak (too small)
MIN_LEAF = 20            # a leaf needs at least this many breaths: no rules learned from a handful of breaths
DEPTHS = [2, 3, 4, 5, 6, 8]
SEED = 0


def load(path):
    with gzip.open(path, "rt") as f:
        rows = list(csv.DictReader(f))
    keep = [r for r in rows if not (r["cls_name"] == "leak" and float(r["leak_true"]) < LEAK_MIN)]
    X = np.array([[float(r[k]) for k in FEATURES] for r in keep])
    y = np.array([int(r["cls"]) for r in keep])
    g = np.array([int(r["scen"]) for r in keep])
    return X, y, g, len(rows) - len(keep), keep


def make_tree(depth):
    return DecisionTreeClassifier(max_depth=depth, min_samples_leaf=MIN_LEAF, class_weight="balanced",
                                  random_state=SEED)


def confusion(y, p):
    m = np.zeros((len(CLASSES), len(CLASSES)), dtype=int)
    for a, b in zip(y, p):
        m[a, b] += 1
    return m


def fmt_confusion(m):
    w = max(len(c) for c in CLASSES) + 2
    out = ["true \\ predicted".ljust(w + 6) + "".join(c.rjust(w) for c in CLASSES) + "   recall"]
    for i, c in enumerate(CLASSES):
        rec = m[i, i] / m[i].sum() if m[i].sum() else float("nan")
        out.append(c.ljust(w + 6) + "".join(str(v).rjust(w) for v in m[i]) + f"   {100 * rec:5.1f} %")
    prec = [m[i, i] / m[:, i].sum() if m[:, i].sum() else float("nan") for i in range(len(CLASSES))]
    out.append("precision".ljust(w + 6) + "".join(f"{100 * p:5.1f} %".rjust(w) for p in prec))
    return "\n".join(out)


def export_c(clf, path):
    t = clf.tree_
    n = t.node_count
    value = t.value[:, 0, :]
    value = value / value.sum(axis=1, keepdims=True)  # fraction of (class-weighted) breaths per class in the node
    feat = [int(f) if t.children_left[i] != -1 else -1 for i, f in enumerate(t.feature)]
    L = [
        "/* copilot_tree.h - GENERATED by scripts/copilot_train.py on %s. Do not edit by hand." % datetime.date.today(),
        " *",
        " * Decision tree learned offline (scikit-learn %s, depth %d, %d nodes, %d leaves) from %s." % (
            sklearn.__version__, clf.get_depth(), n, clf.get_n_leaves(), "results/copilot/bench_train.csv"),
        " * Node i: if feature[i] == -1 it is a leaf and value[i][] holds the fraction of each class in it.",
        " * Otherwise: x[feature[i]] <= threshold[i] goes to left[i], else to right[i].",
        " * scikit-learn compares the feature as a 32-bit float: (double)(float)x <= threshold.",
        " * Features (breath_feat.h): " + ", ".join(FEATURES) + ".",
        " * Classes: " + ", ".join(f"{i} {c}" for i, c in enumerate(CLASSES)) + ". */",
        "#ifndef COPILOT_TREE_H",
        "#define COPILOT_TREE_H",
        "",
        "#include <stdint.h>",
        "",
        "#define CT_N_NODES %d" % n,
        "#define CT_N_FEATURES %d" % len(FEATURES),
        "#define CT_N_CLASSES %d" % len(CLASSES),
        "#define CT_DEPTH %d" % clf.get_depth(),
        "",
        "static const int16_t ct_feature[CT_N_NODES] = { %s };" % ", ".join(map(str, feat)),
        "static const double ct_threshold[CT_N_NODES] = {",
    ]
    L += ["    %r," % float(v) for v in t.threshold]
    L += ["};",
          "static const int16_t ct_left[CT_N_NODES] = { %s };" % ", ".join(map(str, t.children_left)),
          "static const int16_t ct_right[CT_N_NODES] = { %s };" % ", ".join(map(str, t.children_right)),
          "static const float ct_value[CT_N_NODES][CT_N_CLASSES] = {"]
    L += ["    { %s }," % ", ".join("%.6ff" % v for v in row) for row in value]
    L += ["};", "", "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(L))


def export_vectors(clf, X, path, rng, n_random=1500):
    """Held-out breaths + one 'edge' vector per split node (the feature exactly at the threshold)."""
    t = clf.tree_
    idx = rng.choice(len(X), size=min(n_random, len(X)), replace=False)
    V = [X[i].copy() for i in idx]
    for node in range(t.node_count):
        if t.children_left[node] == -1:
            continue
        v = X[rng.integers(len(X))].copy()
        v[t.feature[node]] = t.threshold[node]  # the C code must compare exactly like sklearn here
        V.append(v)
    V = np.array(V)
    pred = clf.predict(V)
    conf = clf.predict_proba(V).max(axis=1)
    L = ["/* test_vectors.h - GENERATED by scripts/copilot_train.py: inputs and scikit-learn's answers. */",
         "#define TV_N %d" % len(V),
         "#define TV_N_EDGE %d" % (len(V) - len(idx)),
         "static const double tv_x[TV_N][%d] = {" % len(FEATURES)]
    L += ["    { %s }," % ", ".join(repr(float(a)) for a in v) for v in V]
    L += ["};", "static const int tv_class[TV_N] = { %s };" % ", ".join(map(str, pred)),
          "static const double tv_conf[TV_N] = { %s };" % ", ".join("%.6f" % c for c in conf), ""]
    with open(path, "w") as f:
        f.write("\n".join(L))
    return len(V)


def main():
    Xtr, ytr, gtr, drop_tr, _ = load(os.path.join(RES, "bench_train.csv.gz"))
    Xte, yte, gte, drop_te, rows_te = load(os.path.join(RES, "bench_test.csv.gz"))
    rep = []
    P = rep.append
    P("Copilot decision tree - training report (%s, scikit-learn %s)" % (datetime.date.today(), sklearn.__version__))
    P("")
    P("Data (offline test bench, tools/copilot_gen.c): one row = one breath; one scenario = one patient.")
    P("  train: %d breaths, %d patients (seed 1); test: %d breaths, %d patients (seed 2, never seen in training)" % (
        len(ytr), len(set(gtr)), len(yte), len(set(gte))))
    P("  dropped 'leak' breaths with true leak < %d %% of Vt: %d train, %d test" % (100 * LEAK_MIN, drop_tr, drop_te))
    for i, c in enumerate(CLASSES):
        P("  %-7s train %5d   test %5d" % (c, (ytr == i).sum(), (yte == i).sum()))
    P("")
    P("Depth chosen by 5-fold cross-validation grouped by patient (a patient is never in train and validation):")
    cv = {}
    for d in DEPTHS:
        accs = []
        for a, b in GroupKFold(n_splits=5).split(Xtr, ytr, gtr):
            m = make_tree(d).fit(Xtr[a], ytr[a])
            p = m.predict(Xtr[b])
            accs.append(np.mean([np.mean(p[ytr[b] == k] == k) for k in range(len(CLASSES))]))  # balanced accuracy
        cv[d] = (np.mean(accs), np.std(accs))
        P("  depth %d: balanced accuracy %.2f %% +- %.2f" % (d, 100 * cv[d][0], 100 * cv[d][1]))
    best = max(v[0] for v in cv.values())
    depth = min(d for d in DEPTHS if cv[d][0] >= best - 0.005)
    P("  -> depth %d (the smallest within 0.5 points of the best: a tree a person can audit)" % depth)
    P("")

    clf = make_tree(depth).fit(Xtr, ytr)
    pte = clf.predict(Xte)
    m = confusion(yte, pte)
    bal = np.mean([m[i, i] / m[i].sum() for i in range(len(CLASSES))])
    P("Final tree: depth %d, %d nodes, %d leaves, min %d breaths per leaf, class_weight=balanced" % (
        clf.get_depth(), clf.tree_.node_count, clf.get_n_leaves(), MIN_LEAF))
    P("")
    P("Test set (%d new patients), per breath: accuracy %.2f %%, balanced accuracy %.2f %%" % (len(set(gte)),
        100 * np.mean(pte == yte), 100 * bal))
    P(fmt_confusion(m))
    P("")
    # what safety_mon will actually act on: the same class in >= 3 of the last 5 breaths of a patient
    by = {}
    for r, p in zip([r for r in rows_te if not (r["cls_name"] == "leak" and float(r["leak_true"]) < LEAK_MIN)], pte):
        by.setdefault(int(r["scen"]), []).append((int(r["cls"]), int(p)))
    per_pat = []
    for s, lst in by.items():
        last = [p for _, p in lst[-5:]]
        votes = [last.count(k) for k in range(len(CLASSES))]
        k = int(np.argmax(votes))
        per_pat.append((lst[0][0], k if votes[k] >= 3 else -1))
    mp = confusion([a for a, b in per_pat if b >= 0], [b for a, b in per_pat if b >= 0])
    undecided = sum(1 for _, b in per_pat if b < 0)
    P("Per patient with the persistence rule safety_mon uses (same class in >= 3 of the last 5 breaths):")
    P("  %d patients, %d without a persistent class (no suggestion)" % (len(per_pat), undecided))
    P(fmt_confusion(mp))
    P("")
    P("Feature importances (how much each feature reduces impurity in the tree):")
    for f, w in sorted(zip(FEATURES, clf.feature_importances_), key=lambda z: -z[1]):
        P("  %-10s %.3f" % (f, w))
    P("")
    P("Limits of this evaluation: train and test come from the same simulator (different patients and noise), so")
    P("this is an upper bound. The external test is in QNX against Pulse (results/copilot/qnx_*), a different")
    P("patient model the tree never saw. Breaths cut by the VCV pressure limit are not classified (see copilot_gen.c).")

    export_c(clf, os.path.join(ROOT, "src", "copilot_tree.h"))
    nv = export_vectors(clf, Xte, os.path.join(ROOT, "tareas", "05_tree", "test_vectors.h"), np.random.default_rng(SEED))
    with open(os.path.join(RES, "tree_rules.txt"), "w") as f:
        f.write("Copilot decision tree (class weights balanced; value = class fractions). Classes: %s\n\n" % CLASSES)
        f.write(export_text(clf, feature_names=FEATURES, show_weights=False, decimals=4))
    P("")
    P("Exported: src/copilot_tree.h, tareas/05_tree/test_vectors.h (%d vectors), results/copilot/tree_rules.txt" % nv)
    text = "\n".join(rep) + "\n"
    with open(os.path.join(RES, "train_report.txt"), "w") as f:
        f.write(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
